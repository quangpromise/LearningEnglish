/// nhạc; danh sách chủ đề chỉ tham khảo các chủ đề tiếng Anh giao tiếp phổ
/// biến (gia đình, thời tiết, mua sắm...) - đây là kiến thức chung, không
/// thuộc về bất kỳ nguồn cụ thể nào.
class VocabWord {
  const VocabWord({
    required this.en,
    required this.ipa,
    required this.vi,
    required this.exampleEn,
    required this.exampleVi,
  });

  final String en;
  final String ipa;
  final String vi;
  final String exampleEn;
  final String exampleVi;
}

class VocabTopic {
  const VocabTopic({
    required this.name,
    required this.nameEn,
    required this.icon,
    required this.color,
    required this.words,
  });

  final String name;

  /// Ten chu de bang tieng Anh - hien thi thay [name] khi ngon ngu giao
  /// dien la English (xem topicLabel() ben duoi).
  final String nameEn;
  final IconData icon;
  final Color color;
  final List<VocabWord> words;
}

/// Ten chu de theo ngon ngu giao dien hien tai - dung o moi noi hien thi
/// ten chu de (danh sach, man chi tiet, quiz) thay vi doc thang [VocabTopic.name].
String topicLabel(WidgetRef ref, VocabTopic topic) =>
    ref.watch(appLanguageProvider) == AppLanguage.en
    ? topic.nameEn
    : topic.name;

